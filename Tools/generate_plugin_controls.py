#!/usr/bin/env python3
"""Write Source/PluginControls.h, the plug-in's parameter table, from Assets/controls.json.

  python3 Tools/generate_plugin_controls.py           # rewrite the header
  python3 Tools/generate_plugin_controls.py --check   # fail if it is stale

A control's startup_default, where it has one, is the plug-in default: it is
what the Rack's Init and factory patches store, while `default` is what the
Rack assumes for an old patch that lacks the property.

The control ids are the plug-in parameter IDs and the Rack property names, so
hosts and Reason recall the same names. Never rename or reuse one.
"""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "Assets/controls.json"
TARGET = ROOT / "Source/PluginControls.h"


def number(value) -> str:
    text = repr(float(value))
    return text if "e" in text or "." in text else text + ".0"


def render() -> str:
    controls = json.loads(SOURCE.read_text(encoding="utf-8"))["controls"]
    lines = [
        "// Generated by Tools/generate_plugin_controls.py from Assets/controls.json; do not edit.",
        "#pragma once",
        "",
        "#include <array>",
        "#include <string_view>",
        "",
        "namespace press78 {",
        "",
        "struct PluginControl {",
        "    std::string_view id, label;",
        "    double minimum, maximum, defaultValue;",
        "    bool integer, patch, hidden; // hidden: not on the Rack panel, so not in the editor",
        "    std::string_view options; // '|'-separated choice names, empty for numbers",
        "};",
        "",
        f"inline constexpr std::array<PluginControl, {len(controls)}> kPluginControls{{{{",
    ]
    for c in controls:
        options = "|".join(c.get("options", []))
        lines.append(
            f'    {{"{c["id"]}", "{c["label"]}", {number(c["min"])}, {number(c["max"])}, '
            f'{number(c.get("startup_default", c["default"]))}, {str(bool(c["integer"])).lower()}, '
            f'{str(c["target"] == "patch").lower()}, {str(bool(c.get("hidden", False))).lower()}, "{options}"}},')
    lines += [
        "}};",
        "",
        "// Index of a control id; unknown ids are a compile-time error where constant-evaluated.",
        "constexpr std::size_t controlIndex(std::string_view id) {",
        "    for (std::size_t i = 0; i < kPluginControls.size(); ++i)",
        "        if (kPluginControls[i].id == id) return i;",
        "    throw \"unknown Press78 control id\";",
        "}",
        "",
        "} // namespace press78",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = render()
    if args.check:
        if TARGET.read_text(encoding="utf-8") != text:
            print(f"{TARGET.relative_to(ROOT)} is stale; run {Path(__file__).name}", file=sys.stderr)
            return 1
        print(f"{TARGET.relative_to(ROOT)} matches {SOURCE.relative_to(ROOT)}")
        return 0
    TARGET.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
