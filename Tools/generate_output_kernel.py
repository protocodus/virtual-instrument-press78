#!/usr/bin/env python3
"""Generate immutable fixed-output Kaiser-sinc table; no runtime initialization."""
import argparse, hashlib, math, pathlib, struct
P=pathlib.Path(__file__).resolve().parents[1]/"Source"/"DSP"

def i0(x):
    term=total=1.0
    for k in range(1,200):
        term *= (x*x/4)/(k*k); total += term
        if term < total*1e-18: return total
    raise RuntimeError('I0 failed to converge')

def generate(check=False):
    values=[]
    for j in range(96*1024+1):
        x=j/1024
        sinc=1 if x==0 else math.sin(math.pi*.95*x)/(math.pi*.95*x)
        y=.95*sinc*i0(10*math.sqrt(max(0,1-(x/96)**2)))/i0(10)
        values.append(struct.unpack('f',struct.pack('f',y))[0])
    tokens=[]
    for value in values:
        token=format(value,'.9g')
        if '.' not in token and 'e' not in token: token+='.0'
        tokens.append(token+'f')
    lines=[', '.join(tokens[i:i+8])+',' for i in range(0,len(tokens),8)]
    content='''// Generated by Tools/generate_output_kernel.py. Fixed output-bus reconstruction.
// h(u)=.95*sinc(.95*u)*I0(10*sqrt(1-(u/96)^2))/I0(10), |u|<=96.
// 1024 intervals per input sample. Immutable, shared read-only; no constructors.
#pragma once
#include <array>
namespace press78::output_bus_detail {
inline constexpr std::array<float,98305> kKernel = {{
'''+ '\n'.join(lines)+'\n}};\n}\n'
    path=P/'OutputKernelTable.h'
    if check:
        if not path.exists() or path.read_text()!=content:
            raise SystemExit('OutputKernelTable.h differs from deterministic generator')
        print('Output kernel matches deterministic generator')
    else:
        path.write_text(content)
        print(hashlib.sha256(content.encode()).hexdigest())
if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    generate(parser.parse_args().check)
