#!/usr/bin/env python3
"""Generate fixed causal halfband interpolation/decimation for the analog circuit.

This policy improves numerical integration of the documented PSS480 surrogate;
it does not identify a PSS780 DAC clock, transfer law or complete output board.
No noise source or fitted gain is involved. The generated header wraps the
existing AnalogOutput without changing that circuit or its coefficient source.
"""
import argparse
from pathlib import Path
import numpy as np
from scipy import signal

ROOT = Path(__file__).resolve().parents[1]


def halfband_coefficients():
    result = {}
    for name, size in (("outer", 129), ("inner", 65)):
        h = signal.firwin(size, 0.5, window=("kaiser", 10.0), scale=False)
        h[(np.arange(size) - size // 2) % 2 == 0] = 0.0
        h[size // 2] = 0.5
        h[1::2] *= 0.5 / h[1::2].sum()
        assert abs(h.sum() - 1.0) < 1e-14
        assert np.array_equal(h, h[::-1])
        result[name] = h
    return result


TEMPLATE = r"""#pragma once
// Generated by Tools/generate_analog_oversampling.py; do not hand-edit.
// PSS480 volume-pot-top analog surrogate, not a recovered PSS780 board or DAC.
// Fixed 4x integration and two causal 2x halfband stages each way.
// Outer FIR:129 taps; inner FIR:65 taps. Explicit roundtrip FIR delay:80 host frames.
// No noise sources, allocations, input-dependent configuration, or per-block reset.
#include "AnalogOutput.h"
#include <array>
#include <algorithm>
#include <cstddef>

namespace press78 {
namespace analog_oversampling_detail {
@COEFFICIENTS@

// Mirrored bounded history; newest sample is data[write_], prior samples follow.
template<std::size_t N> class History {
public:
    void reset() noexcept { data_.fill(0.0); write_=0; }
    void push(double value) noexcept {
        write_ = write_==0 ? N-1 : write_-1;
        data_[write_]=value; data_[write_+N]=value;
    }
    double at(std::size_t lag) const noexcept {return data_[write_+lag];}
private:
    std::array<double,2*N> data_{};
    std::size_t write_=0;
};

template<std::size_t M> class Up2 {
public:
    explicit Up2(const std::array<double,M>& odd) noexcept : odd_(odd) {}
    void reset() noexcept {history_.reset();}
    std::array<double,2> process(double input) noexcept {
        history_.push(input);
        double interpolated=0;
        for(std::size_t i=0;i<M;++i)interpolated+=2.0*odd_[i]*history_.at(i);
        return {{history_.at(M/2),interpolated}};
    }
private:
    const std::array<double,M>& odd_;
    History<M> history_;
};

template<std::size_t M> class Down2 {
public:
    explicit Down2(const std::array<double,M>& odd) noexcept : odd_(odd) {}
    void reset() noexcept {history_.reset();}
    // Return the even-time output, then retain the following odd-time sample.
    // This fixes decimation phase0 at both stages, preserving80-frame latency.
    double process(double even,double odd) noexcept {
        history_.push(even);
        double output=.5*history_.at(M);
        for(std::size_t i=0;i<M;++i)output+=odd_[i]*history_.at(2*i+1);
        history_.push(odd);
        return output;
    }
private:
    const std::array<double,M>& odd_;
    History<2*M+1> history_;
};

} // namespace analog_oversampling_detail

class OversampledAnalogOutput {
public:
    static constexpr int kLatencyFrames=80;
    OversampledAnalogOutput() noexcept
        : upOuter_(analog_oversampling_detail::outerOdd),
          upInner_(analog_oversampling_detail::innerOdd),
          downInner_(analog_oversampling_detail::innerOdd),
          downOuter_(analog_oversampling_detail::outerOdd) {}
    void prepare(double hostRate) noexcept {
        const double rate=std::isfinite(hostRate)?std::clamp(hostRate,8000.0,192000.0):48000.0;
        analog_.prepare(rate*4.0);reset();
    }
    void reset() noexcept {upOuter_.reset();upInner_.reset();downInner_.reset();downOuter_.reset();analog_.reset();}
    double process(double input) noexcept {
        const auto outer=upOuter_.process(input);
        const auto a=upInner_.process(outer[0]);
        const auto b=upInner_.process(outer[1]);
        const double a0=analog_.process(a[0]),a1=analog_.process(a[1]);
        const double b0=analog_.process(b[0]),b1=analog_.process(b[1]);
        const double even=downInner_.process(a0,a1);
        const double odd=downInner_.process(b0,b1);
        return downOuter_.process(even,odd);
    }
    void processBlock(const double* input,double* output,std::size_t count) noexcept {
        for(std::size_t i=0;i<count;++i)output[i]=process(input[i]);
    }
private:
    analog_oversampling_detail::Up2<64> upOuter_;
    analog_oversampling_detail::Up2<32> upInner_;
    analog_oversampling_detail::Down2<32> downInner_;
    analog_oversampling_detail::Down2<64> downOuter_;
    press78::AnalogOutput analog_;
};
} // namespace press78
"""


def render_header():
    arrays = []
    for name, h in halfband_coefficients().items():
        rows = ",\n".join("    " + format(v, ".17g") for v in h[1::2])
        arrays.append(f"inline constexpr std::array<double,{len(h)//2}> {name}Odd{{{{\n{rows}\n}}}};")
    return TEMPLATE.replace("@COEFFICIENTS@", "\n".join(arrays))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = ROOT / "Source/DSP/OversampledAnalogOutput.h"
    content = render_header()
    if args.check:
        assert target.read_text() == content, "Stale OversampledAnalogOutput.h"
        print("Fixed 4x analog halfband coefficients are current")
    else:
        target.write_text(content)
        print(f"Generated {target}")


if __name__ == "__main__":
    main()
