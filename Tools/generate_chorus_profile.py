"""Freeze the measured effective v3 transfer; no physical BBD identification."""
from pathlib import Path
import argparse
import hashlib
import json
import math

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'Reference/Python/circuit/video_chorus_profile.json'
TARGET = ROOT / 'Source/DSP/RecordedChorusProfile.h'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    profile = json.loads(SOURCE.read_text())
    delay = profile['delay_ms']
    # Preserve the frozen IEEE addition order across Python versions. Python
    # 3.12 changed sum(float) to compensated summation (a one-ULP difference).
    excursion = 0.0
    for key in ('sin_1', 'cos_1', 'sin_2', 'cos_2'):
        excursion += abs(delay[key])
    fields = {
        'rateHz': profile['lfo_hz'],
        'meanMs': delay['mean'],
        'sin1Ms': delay['sin_1'], 'cos1Ms': delay['cos_1'],
        'sin2Ms': delay['sin_2'], 'cos2Ms': delay['cos_2'],
        'depthMs': math.hypot(delay['sin_1'], delay['cos_1']),
        'wetGain': profile['wet_gain'], 'midLeakGain': profile['mid_leak_gain'],
        'excursionBoundMs': excursion,
    }
    content = '''#pragma once
// Generated by Tools/generate_chorus_profile.py; do not edit constants.
// Frozen recording-calibrated effective mid-to-side transfer, NOT a recovered
// PSS780 BBD circuit. Identified band100-4000Hz; other frequencies extrapolate.
// Source recording: https://www.youtube.com/watch?v=ONfIvtDOog0
// Profile SHA256: PROFILE_HASH
namespace press78 {
struct RecordedChorusProfile {
FIELDS
};
} // namespace press78
'''.replace('PROFILE_HASH', hashlib.sha256(SOURCE.read_bytes()).hexdigest()).replace(
        'FIELDS', '\n'.join(f'    static constexpr double {k} = {v:.17g};' for k, v in fields.items()))
    if args.check:
        assert TARGET.read_text() == content, 'Stale recorded chorus profile'
    else:
        TARGET.write_text(content)
    print('Frozen recorded chorus profile checked')


if __name__ == '__main__':
    main()
