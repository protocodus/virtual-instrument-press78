#!/usr/bin/env python3
"""Generate the exact reduced PSS480 resistor/opamp noise MIMO realization.

The dynamics come from the preserved circuit MNA, not a fitted recording PSD.
Continuous states are scaled for conditioning; native prepare uses the bilinear
transform. The reference RMS is one fixed continuous20–20kHz circuit integral.
"""
from pathlib import Path
import sys,json,hashlib
import numpy as np
from scipy import linalg,signal
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'Reference/Python'))
from circuit.model import build_pss480_circuit
from circuit.output_stage import KB,noise_spectrum


def matrices():
 c,_=build_pss480_circuit();inputs=[];names=[]
 for part in c.parts:
  b=np.zeros(len(c.G))
  if part['kind']=='R' and not part['name'].endswith('_Rin'):
   for node,sign in ((part['a'],1),(part['b'],-1)):
    if node!='0':b[c.ids[node]]+=sign
   density=4*KB*300/part['value']
  elif part['kind']=='opamp':
   b[c.names.index('I_'+part['name'])]=part['dc_gain'];density=1e-16
  else:continue
  names.append(part['name']);inputs.append(b*np.sqrt(density))
 c.B=np.array(inputs).T
 left=c.state_space('volume_top_l');right=c.state_space('volume_top_r')
 A,B=left.A,left.B;C=np.vstack((left.C,right.C));D=np.vstack((left.D,right.D))
 # Exact change of coordinates: stationary state variance near unity.
 P=linalg.solve_continuous_lyapunov(A,-B@B.T)
 scale=np.sqrt(np.maximum(np.diag(P),1e-30))
 return A/scale[:,None]*scale[None,:],B/scale[:,None],C*scale[None,:],D,names


def main():
 A,B,C,D,names=matrices()
 hz=np.geomspace(20,20000,1000);cov,_=noise_spectrum(hz)
 reference=float(np.sqrt(np.trapz(cov[:,0,0].real,hz)))
 source=ROOT/'Source/DSP/CircuitNoise.h'
 def arr(name,x):
  rows,cols=x.shape
  return f'    inline static constexpr double {name}[{rows}][{cols}] = {{\n'+''.join('        {'+', '.join(f'{n:.17g}' for n in row)+'},\n' for row in x)+'    };\n'
 head='''// Generated by Tools/generate_circuit_noise.py; do not hand-edit coefficients.
#pragma once
#include <array>
#include <algorithm>
#include <cmath>
#include <cstdint>

namespace press78 {
// Original PSS480 network, not an identified PSS780 noise floor.
// 300K Johnson noise + independent10nV/sqrt(Hz) white opamp input noise.
// No opamp current/1/f, DAC, BBD, supply or captured-recording noise.
// Output is electrical volts. Mapping it to model units remains an assumption.
// Bilinear discretization warps HF response; kReferenceRmsVolts is NEVER changed
// per sample rate, block, voice or rendered performance.
class CircuitNoise {
public:
    static constexpr unsigned kStates=12, kSources=14;
'''
 head+=f'    static constexpr double kReferenceRmsVolts={reference:.17g};\n'
 head+='''    void prepare(double sampleRate, std::uint32_t seed=0x7804558U) noexcept {
        sampleRate_=std::isfinite(sampleRate)?std::clamp(sampleRate,8000.0,192000.0):48000.0;
        const double dt=1.0/sampleRate_;
        double aug[kStates][2*kStates]{};
        for(unsigned i=0;i<kStates;++i)for(unsigned j=0;j<kStates;++j) {
            aug[i][j]=(i==j?1.0:0.0)-.5*dt*continuousA_[i][j];
            aug[i][j+kStates]=(i==j?1.0:0.0);
        }
        // Fixed-size partial-pivot inverse, used only at preparation time.
        for(unsigned p=0;p<kStates;++p) {
            unsigned pivot=p;
            for(unsigned i=p+1;i<kStates;++i)
                if(std::abs(aug[i][p])>std::abs(aug[pivot][p]))pivot=i;
            if(pivot!=p)for(unsigned j=0;j<2*kStates;++j)std::swap(aug[p][j],aug[pivot][j]);
            const double divisor=aug[p][p];
            for(unsigned j=0;j<2*kStates;++j)aug[p][j]/=divisor;
            for(unsigned i=0;i<kStates;++i)if(i!=p) {
                const double amount=aug[i][p];
                for(unsigned j=0;j<2*kStates;++j)aug[i][j]-=amount*aug[p][j];
            }
        }
        const double whiteScale=std::sqrt(sampleRate_*.5);
        for(unsigned i=0;i<kStates;++i) {
            for(unsigned j=0;j<kStates;++j)ad_[i][j]=2*aug[i][j+kStates]-(i==j?1.0:0.0);
            for(unsigned j=0;j<kSources;++j) {
                bd_[i][j]=0;
                for(unsigned k=0;k<kStates;++k)bd_[i][j]+=aug[i][k+kStates]*continuousB_[k][j]*dt*whiteScale;
            }
        }
        for(unsigned o=0;o<2;++o) {
            for(unsigned j=0;j<kStates;++j) {
                cd_[o][j]=0;
                for(unsigned k=0;k<kStates;++k)cd_[o][j]+=continuousC_[o][k]*aug[k][j+kStates];
            }
            for(unsigned j=0;j<kSources;++j) {
                dd_[o][j]=continuousD_[o][j]*whiteScale;
                for(unsigned k=0;k<kStates;++k)dd_[o][j]+=.5*continuousC_[o][k]*bd_[k][j];
            }
        }
        reset(seed);
    }
    void reset(std::uint32_t seed=0x7804558U) noexcept {
        state_.fill(0.0);random_=seed?seed:0x7804558U;
    }
    // Unit-variance independent PRNG innovations approximate white sources.
    // Uniform excitation reproduces the second-order circuit noise model;
    // it is not a claim that physical thermal noise has a uniform distribution.
    std::array<double,2> process() noexcept {
        std::array<double,kSources> white{};
        for(auto& x:white) {
            random_^=random_<<13; random_^=random_>>17; random_^=random_<<5;
            x=(static_cast<double>(random_)/4294967296.0*2.0-1.0)*1.7320508075688772935;
        }
        return processWhite(white);
    }
    // Deterministic linear probe. Innovations must have variance1; output V.
    std::array<double,2> processWhite(const std::array<double,kSources>& white) noexcept {
        std::array<double,2> out{};
        std::array<double,kStates> next{};
        for(unsigned o=0;o<2;++o) {
            for(unsigned i=0;i<kStates;++i)out[o]+=cd_[o][i]*state_[i];
            for(unsigned i=0;i<kSources;++i)out[o]+=dd_[o][i]*white[i];
        }
        for(unsigned i=0;i<kStates;++i) {
            for(unsigned j=0;j<kStates;++j)next[i]+=ad_[i][j]*state_[j];
            for(unsigned j=0;j<kSources;++j)next[i]+=bd_[i][j]*white[j];
        }
        state_=next;
        return out;
    }
    double sampleRate() const noexcept {return sampleRate_;}
private:
    double ad_[kStates][kStates]{},bd_[kStates][kSources]{};
    double cd_[2][kStates]{},dd_[2][kSources]{};
    std::array<double,kStates> state_{};
    double sampleRate_=48000.0;
    std::uint32_t random_=0x7804558U;
'''
 head+=arr('continuousA_',A)+arr('continuousB_',B)+arr('continuousC_',C)+arr('continuousD_',D)+'};\n} // namespace press78\n'
 source.write_text(head)
 report={'kind':'Exact reduced MNA PSS480 white-noise network; related hardware only','temperature_kelvin':300,'opamp_en_v_per_sqrt_hz':1e-8,'states':12,'sources':names,'fixed_normalization_rms_v':reference,'reference_band_hz':[20,20000],'discretization':'bilinear; unit-variance innovations scaled sqrt(fs/2) for one-sided physical PSD; no per-rate gain correction','source_sha256':{str(p.relative_to(ROOT)):hashlib.sha256(p.read_bytes()).hexdigest() for p in [ROOT/'Reference/Python/circuit/model.py',ROOT/'Reference/Python/circuit/output_stage.py',Path(__file__),source]},'rates':{}}
 for fs in [8000,44100,48000,96000,192000]:
  ad,bd,cd,dd,_=signal.cont2discrete((A,B,C,D),1/fs,method='bilinear')
  f=np.geomspace(20,min(20000,fs*.49),1000);fa=fs/np.pi*np.tan(np.pi*f/fs);target,_=noise_spectrum(fa)
  t=np.array([cd@np.linalg.solve(np.exp(2j*np.pi*ff/fs)*np.eye(len(A))-ad,bd)+dd for ff in f]);v=np.einsum('fcs,fds->fcd',t,t.conj())
  error=float(np.max(abs(v-target)/np.maximum(abs(target[:,0,0,None,None]),1e-30)))
  assert error<1e-8
  report['rates'][str(fs)]={'band_hz':[20,float(f[-1])],'max_relative_mapped_covariance_error':error,'predicted_rms_v':np.sqrt(np.trapz(v[:,[0,1],[0,1]].real,f,axis=0)).tolist(),'predicted_correlation':float(np.trapz(v[:,0,1].real,f)/np.trapz(v[:,0,0].real,f)),'maximum_pole_radius':float(np.max(abs(np.linalg.eigvals(ad))))}
 out=ROOT/'Tests/results/circuit-noise-generated.json';out.parent.mkdir(parents=True,exist_ok=True);out.write_text(json.dumps(report,indent=2)+'\n')
 print('Generated12-state14-source CircuitNoise.h; mapped covariance error<1e-8 across5 rates.')
if __name__=='__main__':main()
