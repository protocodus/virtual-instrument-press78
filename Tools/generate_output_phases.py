#!/usr/bin/env python3
"""Generate the output bus's precomputed kernel rows for common host rates.

At an integer host rate the bus reads the 48 kHz history at fractions
rem/rate, rem a multiple of gcd(48000, rate): rate/gcd distinct phases
(147 at 44.1 kHz). Each row here is OutputSRC::coefficient(relative - f)
for relative = -half..half, evaluated with the same IEEE double operations
in the same order, so a row read is bit for bit the coefficient computed
in the loop. Press78.OutputBus checks the rows against coefficient()."""
import argparse, hashlib, math, pathlib, re, struct
P = pathlib.Path(__file__).resolve().parents[1] / "Source" / "DSP"
RATES = (44100,)

def kernel():
    text = (P / "OutputKernelTable.h").read_text()
    body = text[text.index("{{") + 2:text.index("}}")]
    values = [struct.unpack('f', struct.pack('f', float(t[:-1])))[0] for t in re.findall(r'[-0-9.e+]+f', body)]
    if len(values) != 98305: raise SystemExit('unexpected kernel length')
    return values

def rows(rate, k):
    ratio = min(1.0, rate / 48000.0)
    half = math.ceil(96.0 / ratio)
    g = math.gcd(48000, rate)
    def coefficient(distance):
        u = abs(ratio * distance) * 1024.0
        if u > 98304.0: return 0.0
        i = int(u)
        if i >= 98304: return ratio * k[98304]
        fraction = u - float(i)
        return ratio * (k[i] + (k[i + 1] - k[i]) * fraction)
    table = []
    for phase in range(rate // g):
        f = float(phase * g) / float(rate)
        table.append([coefficient(float(relative) - f) for relative in range(-half, half + 1)])
    return table, 2 * half + 1

def generate(check=False):
    k = kernel()
    parts = []
    for rate in RATES:
        table, taps = rows(rate, k)
        tokens = [repr(c) for row in table for c in row]
        lines = [', '.join(tokens[i:i + 6]) + ',' for i in range(0, len(tokens), 6)]
        parts.append(f'inline constexpr std::array<double,{len(tokens)}> kPhaseRows{rate} = {{{{\n'
                     + '\n'.join(lines) + '\n}};\n')
        parts.append(f'inline constexpr PhaseTable kPhaseTable{rate}{{{rate}.,{len(table)},{taps},kPhaseRows{rate}.data()}};\n')
    content = '''// Generated by Tools/generate_output_phases.py from OutputKernelTable.h.
// OutputSRC's kernel coefficients precomputed per grid phase for common host
// rates: row p holds coefficient(relative - p/phases) for relative -half..half.
// Immutable, shared read-only; no constructors.
#pragma once
#include <array>
namespace press78::output_bus_detail {
struct PhaseTable { double rate; int phases, taps; const double* rows; };
''' + ''.join(parts) + '}\n'
    path = P / 'OutputPhaseTable.h'
    if check:
        if not path.exists() or path.read_text() != content:
            raise SystemExit('OutputPhaseTable.h differs from deterministic generator')
        print('Output phase table matches deterministic generator')
    else:
        path.write_text(content)
        print(hashlib.sha256(content.encode()).hexdigest())

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    generate(parser.parse_args().check)
